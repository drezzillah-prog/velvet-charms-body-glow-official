import fs from 'node:fs';
const idx=fs.readFileSync('index.html','utf8');
const cat=fs.readFileSync('catalogue.html','utf8');
const state=fs.readFileSync('localization.js','utf8');
const router=fs.readFileSync('multilingual.js','utf8');
const modern=fs.readFileSync('multilingual-modern.js','utf8');
const ro=fs.readFileSync('localization-ro.js','utf8');
if(!idx.includes('localization.js')||!idx.includes('multilingual.js')) throw new Error('home language wiring missing');
if(!cat.includes('localization.js')||!cat.includes('multilingual.js')||!cat.includes('catalogue-root')) throw new Error('catalogue recovery wiring missing');
if(!state.includes('VELVET_GET_LANGUAGE')||state.includes('MutationObserver')) throw new Error('language state must be observer-free');
if(!router.includes("current === 'ro'")||!router.includes('localization-ro.js')||!router.includes('multilingual-modern.js')) throw new Error('single-engine language router missing');
if(!ro.includes('Colecția Refill')||!ro.includes('De ce să alegi Velvet Charms?')) throw new Error('approved Romanian copy missing');
for (const code of ['fr','it','de']) if(!modern.includes(code)) throw new Error(`modern language ${code} missing`);
console.log('Single-engine language/catalogue recovery PASS');
