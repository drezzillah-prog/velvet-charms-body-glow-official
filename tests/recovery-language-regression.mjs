import fs from 'node:fs';
const idx=fs.readFileSync('index.html','utf8');
const cat=fs.readFileSync('catalogue.html','utf8');
const bridge=fs.readFileSync('localization.js','utf8');
const mature=fs.readFileSync('multilingual.js','utf8');
const preserved=fs.readFileSync('multilingual-modern.js','utf8');
const ro=fs.readFileSync('localization-ro.js','utf8');
if(!idx.includes('localization.js')||!idx.includes('multilingual.js')) throw new Error('home language wiring missing');
if(!cat.includes('localization.js')||!cat.includes('multilingual.js')||!cat.includes('catalogue-root')) throw new Error('catalogue recovery wiring missing');
if(!bridge.includes('localization-ro.js')||!bridge.includes('.language-switcher')) throw new Error('Romanian bridge or duplicate-selector cleanup missing');
if(mature!==preserved) throw new Error('multilingual.js must be the preserved mature five-language runtime');
if(!ro.includes('Colecția Refill')||!ro.includes('De ce să alegi Velvet Charms?')) throw new Error('approved Romanian copy missing');
for (const code of ['fr','it','de']) if(!mature.includes(code)) throw new Error(`mature language ${code} missing`);
console.log('Mature language/catalogue runtime PASS');
